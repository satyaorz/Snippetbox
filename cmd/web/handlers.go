// snippetForm is used by both the create and edit snippet forms. The struct
// tags tell the form decoder how to map HTML form values into the different
// struct fields, so here the input with the name "title" is stored in the
// Title field. The struct tag `form:"-"` tells the decoder to completely
// ignore a field during decoding.
type snippetForm struct {
	Title               string `form:"title"`
	Content             string `form:"content"`
	Language            string `form:"language"`
	Visibility          string `form:"visibility"`
	Expires             int    `form:"expires"`
	validator.Validator `form:"-"`
}

// validate runs the checks shared by the create and edit forms.
func (form *snippetForm) validate() {
	form.CheckField(validator.NotBlank(form.Title), "title", "This field cannot be blank")
	form.CheckField(validator.MaxChars(form.Title, 100), "title", "This field cannot be more than 100 characters long")
	form.CheckField(validator.NotBlank(form.Content), "content", "This field cannot be blank")
	// The content column is a MySQL TEXT, which holds at most 64KB.
	form.CheckField(len(form.Content) <= maxContentBytes, "content", "This field cannot be more than 64KB")
	form.CheckField(validator.PermittedValue(form.Language, lang.Values()...), "language", "Please choose a language from the list")
	form.CheckField(validator.PermittedValue(form.Visibility, models.VisibilityPublic, models.VisibilityUnlisted, models.VisibilityPrivate), "visibility", "Please choose a visibility")
}

// maxContentBytes is the largest snippet the database can store.
const maxContentBytes = 65535

// How many snippets to show on each page of the home page listing.
const snippetsPerPage = 10

func (app *application) home(w http.ResponseWriter, r *http.Request) {
	// Read the optional ?q= search term and ?page= number from the query
	// string. Anything that isn't a positive integer is treated as page 1.
	query := strings.TrimSpace(r.URL.Query().Get("q"))
	if utf8.RuneCountInString(query) > 100 {
		query = string([]rune(query)[:100])
	}

	page, err := strconv.Atoi(r.URL.Query().Get("page"))
	if err != nil || page < 1 {
		page = 1
	}

	snippets, total, err := app.snippets.List(query, page, snippetsPerPage)
	if err != nil {
		app.serverError(w, r, err)
		return
	}

	data := app.newTemplateData(r)
	data.Snippets = snippets
	data.Search = query
	data.Pagination = newPagination(query, page, snippetsPerPage, total)

	app.render(w, r, http.StatusOK, "home.tmpl.html", data)
}

