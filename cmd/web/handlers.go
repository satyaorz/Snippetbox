// slugRX matches the format of the random slugs generated by the model, so
// obviously invalid URLs get a 404 without touching the database.
var slugRX = regexp.MustCompile(`^[0-9a-f]{12}$`)

// findViewableSnippet fetches a snippet by slug and checks the current user
// may see it. Private snippets are only visible to their owner; for everyone
// else we pretend they don't exist, so both cases return ErrNoRecord. It's
// shared by the HTML and JSON handlers.
func (app *application) findViewableSnippet(r *http.Request, slug string) (models.Snippet, error) {
	if !slugRX.MatchString(slug) {
		return models.Snippet{}, models.ErrNoRecord
	}

	snippet, err := app.snippets.Get(slug)
	if err != nil {
		return models.Snippet{}, err
	}

	if snippet.Visibility == models.VisibilityPrivate && !app.isOwner(r, snippet) {
		return models.Snippet{}, models.ErrNoRecord
	}

	return snippet, nil
}

// findOwnedSnippet is like findViewableSnippet, but only succeeds if the
// current user owns the snippet. Used for editing and deleting.
func (app *application) findOwnedSnippet(r *http.Request, slug string) (models.Snippet, error) {
	snippet, err := app.findViewableSnippet(r, slug)
	if err != nil {
		return models.Snippet{}, err
	}

	if !app.isOwner(r, snippet) {
		return models.Snippet{}, models.ErrNoRecord
	}

	return snippet, nil
}

// viewableSnippet wraps findViewableSnippet for the HTML handlers, using the
// {slug} wildcard. If ok is false, a 404 or 500 response has been sent.
func (app *application) viewableSnippet(w http.ResponseWriter, r *http.Request) (snippet models.Snippet, ok bool) {
	return app.snippetOrError(w, r, app.findViewableSnippet)
}

// ownedSnippet wraps findOwnedSnippet in the same way.
func (app *application) ownedSnippet(w http.ResponseWriter, r *http.Request) (snippet models.Snippet, ok bool) {
	return app.snippetOrError(w, r, app.findOwnedSnippet)
}

func (app *application) snippetOrError(w http.ResponseWriter, r *http.Request, find func(*http.Request, string) (models.Snippet, error)) (models.Snippet, bool) {
	snippet, err := find(r, r.PathValue("slug"))
	if err != nil {
		if errors.Is(err, models.ErrNoRecord) {
			http.NotFound(w, r)
		} else {
			app.serverError(w, r, err)
		}
		return models.Snippet{}, false
	}

	return snippet, true
}

func (app *application) snippetView(w http.ResponseWriter, r *http.Request) {
	snippet, ok := app.viewableSnippet(w, r)
	if !ok {
		return
	}

	data := app.newTemplateData(r)
	data.Snippet = snippet

	app.render(w, r, http.StatusOK, "view.tmpl.html", data)
}

// snippetRaw serves the snippet content as plain text, which is handy for
// curl or copying code. The X-Content-Type-Options: nosniff header set by
// commonHeaders stops browsers from interpreting it as HTML.
func (app *application) snippetRaw(w http.ResponseWriter, r *http.Request) {
	snippet, ok := app.viewableSnippet(w, r)
	if !ok {
		return
	}

	w.Header().Set("Content-Type", "text/plain; charset=utf-8")
	w.Write([]byte(snippet.Content))
}

func (app *application) snippetCreate(w http.ResponseWriter, r *http.Request) {
	data := app.newTemplateData(r)

	data.Form = snippetForm{
		Visibility: models.VisibilityPublic,
		Expires:    365,
	}

	app.render(w, r, http.StatusOK, "create.tmpl.html", data)
}

func (app *application) snippetCreatePost(w http.ResponseWriter, r *http.Request) {
	var form snippetForm

	err := app.decodePostForm(r, &form)
	if err != nil {
		app.clientError(w, http.StatusBadRequest)
		return
	}

	form.validate()
	form.CheckField(validator.PermittedValue(form.Expires, 1, 7, 365), "expires", "This field must equal 1, 7 or 365")

	if !form.Valid() {
		data := app.newTemplateData(r)
		data.Form = form
		app.render(w, r, http.StatusUnprocessableEntity, "create.tmpl.html", data)
		return
	}

	slug, err := app.snippets.Insert(app.authenticatedUserID(r), form.Title, form.Content, form.Language, form.Visibility, form.Expires)
	if err != nil {
		app.serverError(w, r, err)
		return
	}

	// Use the Put() method to add a string value ("Snippet successfully
	// created!") and the corresponding key ("flash") to the session data.
	app.sessionManager.Put(r.Context(), "flash", "Snippet successfully created!")

	http.Redirect(w, r, fmt.Sprintf("/snippet/view/%s", slug), http.StatusSeeOther)
}

func (app *application) snippetEdit(w http.ResponseWriter, r *http.Request) {
	snippet, ok := app.ownedSnippet(w, r)
	if !ok {
		return
	}

	data := app.newTemplateData(r)
	data.Snippet = snippet
	data.Form = snippetForm{
		Title:      snippet.Title,
		Content:    snippet.Content,
		Language:   snippet.Language,
		Visibility: snippet.Visibility,
	}

	app.render(w, r, http.StatusOK, "edit.tmpl.html", data)
}

func (app *application) snippetEditPost(w http.ResponseWriter, r *http.Request) {
	snippet, ok := app.ownedSnippet(w, r)
	if !ok {
		return
	}

	var form snippetForm

	err := app.decodePostForm(r, &form)
	if err != nil {
		app.clientError(w, http.StatusBadRequest)
		return
	}

	form.validate()

	if !form.Valid() {
		data := app.newTemplateData(r)
		data.Snippet = snippet
		data.Form = form
		app.render(w, r, http.StatusUnprocessableEntity, "edit.tmpl.html", data)
		return
	}

	// The model also checks ownership in its WHERE clause, so even if the
	// snippet changed hands between the two queries we can't edit someone
	// else's snippet.
	err = app.snippets.Update(snippet.Slug, app.authenticatedUserID(r), form.Title, form.Content, form.Language, form.Visibility)
	if err != nil {
		if errors.Is(err, models.ErrNoRecord) {
			http.NotFound(w, r)
		} else {
			app.serverError(w, r, err)
		}
		return
	}

	app.sessionManager.Put(r.Context(), "flash", "Snippet successfully updated!")

	http.Redirect(w, r, fmt.Sprintf("/snippet/view/%s", snippet.Slug), http.StatusSeeOther)
}

func (app *application) snippetDeletePost(w http.ResponseWriter, r *http.Request) {
	snippet, ok := app.ownedSnippet(w, r)
	if !ok {
		return
	}

	err := app.snippets.Delete(snippet.Slug, app.authenticatedUserID(r))
	if err != nil {
		if errors.Is(err, models.ErrNoRecord) {
			http.NotFound(w, r)
		} else {
			app.serverError(w, r, err)
		}
		return
	}

	app.sessionManager.Put(r.Context(), "flash", "Snippet deleted.")

	http.Redirect(w, r, "/account/view", http.StatusSeeOther)
}

// userSignupForm holds the form data and validation errors for the signup
// form.
type userSignupForm struct {
	Name                string `form:"name"`
	Email               string `form:"email"`
	Password            string `form:"password"`
	validator.Validator `form:"-"`
}

func (app *application) userSignup(w http.ResponseWriter, r *http.Request) {
	data := app.newTemplateData(r)
	data.Form = userSignupForm{}
	app.render(w, r, http.StatusOK, "signup.tmpl.html", data)
}

func (app *application) userSignupPost(w http.ResponseWriter, r *http.Request) {
	var form userSignupForm

	err := app.decodePostForm(r, &form)
	if err != nil {
		app.clientError(w, http.StatusBadRequest)
		return
	}

	form.CheckField(validator.NotBlank(form.Name), "name", "This field cannot be blank")
	form.CheckField(validator.NotBlank(form.Email), "email", "This field cannot be blank")
	form.CheckField(validator.Matches(form.Email, validator.EmailRX), "email", "This field must be a valid email address")
	form.CheckField(validator.NotBlank(form.Password), "password", "This field cannot be blank")
	form.CheckField(validator.MinChars(form.Password, 8), "password", "This field must be at least 8 characters long")

	if !form.Valid() {
		data := app.newTemplateData(r)
		data.Form = form
		app.render(w, r, http.StatusUnprocessableEntity, "signup.tmpl.html", data)
		return
	}

	// Try to create a new user record in the database. If the email already
	// exists then add an error message to the form and re-display it.
	err = app.users.Insert(form.Name, form.Email, form.Password)
	if err != nil {
		if errors.Is(err, models.ErrDuplicateEmail) {
			form.AddFieldError("email", "Email address is already in use")

			data := app.newTemplateData(r)
			data.Form = form
			app.render(w, r, http.StatusUnprocessableEntity, "signup.tmpl.html", data)
		} else {
			app.serverError(w, r, err)
		}
		return
	}

	app.sessionManager.Put(r.Context(), "flash", "Your signup was successful. Please log in.")

	http.Redirect(w, r, "/user/login", http.StatusSeeOther)
}

